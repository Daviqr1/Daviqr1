#!/usr/bin/env python3
"""Bake the central URL and device token into a sideload build of the Pulso face.

Garmin Connect only shows/edits app settings for apps installed from the Connect IQ Store.
A face copied to GARMIN/APPS over USB therefore starts with the defaults compiled into the .prg.
This writes (both gitignored):

  config/local/properties.xml   the defaults from config/default with your URL/token
  local.jungle                   points the resource path at config/local

Then build with:   monkeyc -f "monkey.jungle;local.jungle" -d fr255 -o pulso.prg -y developer_key.der

The token ends up readable inside the .prg: treat the file as a secret and revoke the token on
the central if the watch or the file is lost.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path
from xml.sax.saxutils import escape

PROJECT = Path(__file__).resolve().parent.parent


def set_prop(xml: str, pid: str, value: str) -> str:
    pat = re.compile(rf'(<property id="{re.escape(pid)}" type="[a-z]+">)(.*?)(</property>)', re.S)
    if not pat.search(xml):
        raise SystemExit(f"property {pid} not found in config/default/properties.xml")
    return pat.sub(lambda m: m.group(1) + escape(value) + m.group(3), xml, count=1)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--url", required=True, help="central base URL, https://... (without /v1/ingest)")
    ap.add_argument("--token", required=True, help="device token from the central (pulso_dev_...)")
    ap.add_argument("--no-seconds", action="store_true", help="default 'show seconds' to off")
    a = ap.parse_args()
    if not a.url.startswith("https://"):
        raise SystemExit("Connect IQ only talks HTTPS (publicly trusted certificate): use https://")
    if not a.token.startswith("pulso_dev_"):
        print("warning: the central issues tokens starting with pulso_dev_")

    xml = (PROJECT / "config/default/properties.xml").read_text(encoding="utf-8")
    xml = set_prop(xml, "centralUrl", a.url.rstrip("/"))
    xml = set_prop(xml, "deviceToken", a.token)
    if a.no_seconds:
        xml = set_prop(xml, "showSeconds", "false")
    out = PROJECT / "config/local"
    out.mkdir(parents=True, exist_ok=True)
    (out / "properties.xml").write_text(xml, encoding="utf-8")
    (PROJECT / "local.jungle").write_text(
        "# generated by tools/bake_config.py (gitignored): sideload build with baked settings\n"
        "base.resourcePath = resources;config/local\n",
        encoding="utf-8",
    )
    print("wrote", out / "properties.xml", "and", PROJECT / "local.jungle")
    print('build: monkeyc -f "monkey.jungle;local.jungle" -d fr255 -o pulso.prg -y <developer_key.der>')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
